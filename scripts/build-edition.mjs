function run(bin, args) {
	const result = spawnSync(bin, args, { cwd: root, env, stdio: "inherit" });
	if (result.error) throw result.error;
	if (result.status !== 0)
		throw new Error(
			`${bin} ${args.join(" ")} failed (${result.signal ?? result.status ?? "unknown"})`,
		);
}
function cleanGeneratedOutput(directory) {
	if (!new Set(["dist", "dist-electron"]).has(directory)) {
		throw new Error(`Refusing to clean unexpected build output: ${directory}`);
	}
	const output = path.resolve(root, directory);
	if (path.dirname(output) !== root) {
		throw new Error(`Build output escaped the project root: ${directory}`);
	}
	const stat = fs.lstatSync(output, { throwIfNoEntry: false });
	if (!stat) return;
	if (!stat.isDirectory() || stat.isSymbolicLink()) {
		throw new Error(`Refusing to clean non-directory or symlink build output: ${directory}`);
	}
	fs.rmSync(output, { recursive: true });
}
withEditionBuildLock(root, profile.variant, () => {
	assertRuntimeAssets(root);
	// These two ignored directories are generated by tsc/Vite. Remove prior edition
	// bundles while holding the cross-edition build lock so stale chunks cannot ship.
	cleanGeneratedOutput("dist");
	cleanGeneratedOutput("dist-electron");
	const configPath = path.join(root, ".demo-build", `${profile.variant}.json`);
	fs.writeFileSync(configPath, JSON.stringify(config, null, 2));
	run("npx", ["--no-install", "tsc"]);
	run("npx", ["--no-install", "vite", "build"]);
	run("npm", ["run", "licenses:generate"]);
	run("npx", [
		"--no-install",
		"electron-builder",
		"--mac",
		"--dir",
		"--publish",
		"never",
		"--config",
		configPath,
	]);
	console.log(`${name} packaged under release/${profile.variant}. Unsigned/ad-hoc; not notarised.`);
});
